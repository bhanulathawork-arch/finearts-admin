const formatTimeOption = (totalSeconds) => {
  const secondsInDay = 24 * 60 * 60;
  const normalized = ((totalSeconds % secondsInDay) + secondsInDay) % secondsInDay;
  const hour24 = Math.floor(normalized / 3600);
  const minute = Math.floor((normalized % 3600) / 60);
  const second = normalized % 60;
  const ampm = hour24 >= 12 ? "PM" : "AM";
  const hour12 = hour24 % 12 || 12;
  // Keep seconds in the option value for one-second precision, but display
  // only hours and minutes in the dropdown label.
  const displayTime = `${String(hour12).padStart(2, "0")}:${String(minute).padStart(2, "0")}`;
  const storedTime = `${displayTime}:${String(second).padStart(2, "0")}`;
  return { value: `${storedTime}|${ampm}`, label: `${displayTime} ${ampm}` };
};

// Fallback options used until a class is selected (15-minute increments).
const TIME_OPTIONS = Array.from({ length: 96 }, (_, index) =>
  formatTimeOption(index * 15 * 60).value
).map((value) => {
  const [time, ampm] = value.split("|");
  return { value, label: `${time.slice(0, 5)} ${ampm}` };
});

// Parse a class time (24-hour HH:mm[:ss] or 12-hour time with AM/PM)
// into seconds after midnight, so schedule choices can be generated by minute.
const parseClassTimeSeconds = (rawTime) => {
  if (rawTime == null || rawTime === "") return null;
  const raw = String(rawTime).trim();
  const ampmMatch = raw.match(/^(\d{1,2}):(\d{2})(?::(\d{2}))?\s*(AM|PM)$/i);
  if (ampmMatch) {
    let hour = Number(ampmMatch[1]) % 12;
    if (ampmMatch[4].toUpperCase() === "PM") hour += 12;
    const minute = Number(ampmMatch[2]);
    const second = Number(ampmMatch[3] || 0);
    if (minute > 59 || second > 59) return null;
    return hour * 3600 + minute * 60 + second;
  }
  const match = raw.match(/^(\d{1,2}):(\d{2})(?::(\d{2}))?/);
  if (!match) return null;
  const hour = Number(match[1]);
  const minute = Number(match[2]);
  const second = Number(match[3] || 0);
  if (hour > 23 || minute > 59 || second > 59) return null;
  return hour * 3600 + minute * 60 + second;
};

const timeOptionSeconds = (option) => {
  const [time, ampm] = option.value.split("|");
  const [hourText, minuteText, secondText = "0"] = time.split(":");
  let hour = Number(hourText) % 12;
  if (ampm === "PM") hour += 12;
  return hour * 3600 + Number(minuteText) * 60 + Number(secondText);
};

// Return choices only within the selected LIVE class's start/end window,
// using one-minute increments so each displayed hour/minute appears only once.
// End time is included when it falls on a generated minute. For overnight classes,
// the range wraps past midnight.
const getTimeOptionsForClass = (selectedClass) => {
  if (!selectedClass) return TIME_OPTIONS;
  const startSeconds = parseClassTimeSeconds(
    selectedClass.start_time ?? selectedClass.startTime
  );
  let endSeconds = parseClassTimeSeconds(
    selectedClass.end_time ?? selectedClass.endTime ?? selectedClass.finish_time
  );
  if (endSeconds == null && startSeconds != null) {
    const duration = Number(selectedClass.duration ?? selectedClass.duration_minutes);
    if (Number.isFinite(duration) && duration > 0) endSeconds = startSeconds + duration * 60;
  }
  // If API timing data is incomplete, don't guess the permitted window.
  if (startSeconds == null || endSeconds == null) return TIME_OPTIONS;

  const secondsInDay = 24 * 60 * 60;
  if (endSeconds >= secondsInDay) endSeconds %= secondsInDay;
  const crossesMidnight = endSeconds < startSeconds;
  const rangeLength = crossesMidnight
    ? (secondsInDay - startSeconds) + endSeconds
    : endSeconds - startSeconds;
  // Prevent an accidental invalid/full-day duration from creating an enormous list.
  if (rangeLength < 0 || rangeLength > secondsInDay) return TIME_OPTIONS;

  const options = [];
  // The labels display only hours and minutes, so generate one option per minute.
  // This avoids duplicate labels such as "10:00 AM" appearing 60 times.
  for (let offset = 0; offset <= rangeLength; offset += 60) {
    options.push(formatTimeOption(startSeconds + offset));
  }
  return options;
};


